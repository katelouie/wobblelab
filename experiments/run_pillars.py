"""The three pillars on one real benchmark run, end to end.

Pillar 2 in full: reorder + paraphrase (reword the question) + translate, each a
meaning-preserving perturbation, reported per kind. Pillar 1: run-to-run score variance
under sampling. One reproducible call, every number honest to the seed.

Paraphrase and translation are generated by a *perturber* model (here the same tiny local
model, at a higher token budget and some temperature for variety). That carries a meaning-
drift caveat -- a small translator is noisy -- which is itself part of the honest picture.

Run: python experiments/run_pillars.py
"""

from __future__ import annotations

import json
import time
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from wobblelab import (  # noqa: E402
    MultipleChoiceTask,
    OllamaClient,
    ParaphraseWithModel,
    ReorderOptions,
    TranslateWithModel,
    evaluate,
    score_stability,
)
from wobblelab.loaders import load_mmlu  # noqa: E402

MODEL = "qwen3.5:0.8b"
QUANT = "Q8_0"
SUBJECT = "world_religions"
N_ITEMS = 24
LANG = "Chinese"
SEED = 0

# the model under test: controlled config (num_predict 8, enough for a letter)
client = OllamaClient(MODEL, options={"num_predict": 8})
# the perturber: room to generate a translation, some temperature for paraphrase variety
perturber = OllamaClient(MODEL, options={"temperature": 0.7, "num_predict": 128})


def plot(by_kind: dict, runs: list, mean: float, path: Path) -> None:
    plt.rcParams["font.family"] = "DejaVu Sans"
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(11, 4.4), dpi=150)
    fig.patch.set_facecolor("#12141a")
    for ax in (ax1, ax2):
        ax.set_facecolor("#181b23")
        for s in ax.spines.values():
            s.set_color("#3a3f4b")
        ax.tick_params(colors="#8a8f9a")

    kinds = list(by_kind)
    ax1.bar(kinds, [by_kind[k] for k in kinds], color="#f0a63c", width=0.6)
    for i, k in enumerate(kinds):
        ax1.text(
            i,
            by_kind[k] + 0.01,
            f"{by_kind[k]:.0%}",
            ha="center",
            color="#e7dcc8",
            fontsize=10,
        )
    ax1.set_ylim(0, max(0.5, max(by_kind.values()) * 1.25))
    ax1.set_ylabel("answers that flip content", color="#c9b79e")
    ax1.set_title(
        "PILLAR 2 · sensitivity per perturbation kind",
        color="#f6e8ce",
        fontsize=11,
        fontweight="bold",
    )

    xs = list(range(len(runs)))
    ax2.axhline(mean, color="#8fb8d8", lw=1.6, label=f"mean {mean:.0%}")
    ax2.bar(xs, runs, color="#7ec98f", width=0.6)
    for i, v in enumerate(runs):
        ax2.text(i, v + 0.01, f"{v:.0%}", ha="center", color="#e7dcc8", fontsize=9)
    ax2.set_xticks(xs)
    ax2.set_xticklabels([f"run {i + 1}" for i in xs], color="#c9b79e")
    ax2.set_ylim(0, 1)
    ax2.set_ylabel("aggregate accuracy", color="#c9b79e")
    ax2.set_title(
        "PILLAR 1 · same questions, run-to-run (sampling)",
        color="#f6e8ce",
        fontsize=11,
        fontweight="bold",
    )
    ax2.legend(
        facecolor="#181b23", edgecolor="#3a3f4b", labelcolor="#e7dcc8", fontsize=8
    )

    fig.suptitle(
        f"WobbleLab · MMLU:{SUBJECT} · {MODEL} ({QUANT})",
        color="#f6e8ce",
        fontsize=12,
        fontweight="bold",
    )
    fig.tight_layout()
    fig.savefig(path, facecolor=fig.get_facecolor(), bbox_inches="tight")


def main() -> None:
    t0 = time.time()
    items = load_mmlu(SUBJECT, N_ITEMS, SEED)

    # Pillar 2: all three perturbation kinds, log-likelihood scoring (deterministic)
    task = MultipleChoiceTask(
        "ll",
        perturbations=[
            ReorderOptions(),
            ParaphraseWithModel(perturber, n=3),
            TranslateWithModel(perturber, LANG),
        ],
    )
    print(f"running {N_ITEMS} items x (reorder + paraphrase + translate:{LANG}) ...")
    r = evaluate(client, items, benchmark=f"mmlu:{SUBJECT}", task=task)
    print("\n" + r.to_markdown())

    # Pillar 1: run-to-run variance under sampling
    print("running run-to-run stability (gen) ...")
    stab = score_stability(client, items, n_runs=5, scoring="gen", n_rerun=1)
    print(
        f"  runs {[round(x, 3) for x in stab['runs']]}  "
        f"mean {stab['mean']:.3f}  std {stab['std']:.3f}  spread {stab['spread']:.3f}"
    )

    results_dir = Path(__file__).resolve().parent.parent / "results"
    results_dir.mkdir(exist_ok=True)
    plot(
        r.wobble_by_kind,
        stab["runs"],
        stab["mean"],
        results_dir / "pillars_world_religions.png",
    )
    out = {
        "report": r.to_dict(),
        "stability": stab,
        "perturber": perturber.config(),
        "language": LANG,
        "seconds": round(time.time() - t0, 1),
    }
    (results_dir / "pillars_world_religions.json").write_text(json.dumps(out, indent=2))
    print(f"\nwrote results/pillars_world_religions.{{png,json}} in {out['seconds']}s")


if __name__ == "__main__":
    main()
